// >>>>> COMPARISON OPERATOR
// >, >=, <, <=, ==, ===, !=

console.log(10 > 10)
console.log(10 >= 10)
console.log(100 > 200)

// == & ===
// == Mengecek Value Saja
console.log(2 == '2')

// === Mengecek Value dan Tipe Data
console.log(2 === '2')

// != 
console.log (10 != 10) // false
console.log(10 != 5) // true